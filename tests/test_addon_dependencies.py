"""Guard composed folder-addon dependency ownership."""

from __future__ import annotations

import tomllib
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest
from django.apps import AppConfig
from django.core.management.base import CommandError

from angee.compose.runtime import Runtime
from angee.management import dependencies as dependencies_module
from angee.management.commands.angee import Command
from angee.management.dependencies import AddonDependencyGroup, AddonDependencyGroupResult


def _read_toml(path: Path) -> dict[str, Any]:
    """Return the TOML document at ``path`` using the standard-library parser."""

    with path.open("rb") as stream:
        return tomllib.load(stream)


def _app_config(path: Path, name: str, dependencies: tuple[str, ...] | None) -> AppConfig:
    """Return an AppConfig, optionally backed by an addon manifest."""

    path.mkdir(parents=True)
    module = ModuleType(name)
    module.__file__ = str(path / "apps.py")
    module.__path__ = [str(path)]  # type: ignore[attr-defined]
    if dependencies is not None:
        rendered_dependencies = ", ".join(f'"{dependency}"' for dependency in dependencies)
        (path / "addon.toml").write_text(
            f'[addon]\nname = "{name}"\ndependencies = [{rendered_dependencies}]\n',
            encoding="utf-8",
        )
    return AppConfig(name, module)


def test_composed_addon_dependencies_are_written_idempotently(tmp_path: Path) -> None:
    """Only composed folder-addon manifests project into the host group."""

    host = tmp_path / "host"
    host.mkdir()
    pyproject = host / "pyproject.toml"
    pyproject.write_text(
        '[project]\nname = "host"\nversion = "0.0.0"\n\n'
        '[dependency-groups]\ndev = ["pytest>=8"]\n',
        encoding="utf-8",
    )
    addon = _app_config(tmp_path / "fake-addon", "example.fake", ("zeta>=2", "alpha>=1", "alpha>=1"))
    plain_core = _app_config(tmp_path / "fake-core", "angee", None)
    projection = AddonDependencyGroup.from_app_configs((addon, plain_core), project_dir=host)

    assert projection.write() is AddonDependencyGroupResult.WRITTEN
    first_stat = pyproject.stat()
    document = _read_toml(pyproject)
    assert document["dependency-groups"]["dev"] == ["pytest>=8"]
    assert document["dependency-groups"]["addons"] == ["alpha>=1", "zeta>=2"]
    assert pyproject.read_text(encoding="utf-8").count("GENERATED by angee build") == 1

    assert projection.write() is AddonDependencyGroupResult.UNCHANGED
    assert pyproject.stat().st_ino == first_stat.st_ino
    assert pyproject.stat().st_mtime_ns == first_stat.st_mtime_ns


def test_composed_addon_dependencies_are_idempotent_when_group_is_not_last(tmp_path: Path) -> None:
    """A table following the generated group does not cause byte drift."""

    host = tmp_path / "host"
    host.mkdir()
    pyproject = host / "pyproject.toml"
    pyproject.write_text(
        '[project]\nname = "host"\nversion = "0.0.0"\n\n'
        '[dependency-groups]\ndev = ["pytest>=8"]\n\n'
        '[tool.uv]\ndefault-groups = ["dev", "addons"]\n',
        encoding="utf-8",
    )
    addon = _app_config(tmp_path / "fake-addon", "example.fake_mid_group", ("alpha>=1",))
    projection = AddonDependencyGroup.from_app_configs((addon,), project_dir=host)

    assert projection.write() is AddonDependencyGroupResult.WRITTEN
    first_write = pyproject.read_bytes()
    assert projection.write() is AddonDependencyGroupResult.UNCHANGED
    assert pyproject.read_bytes() == first_write


def test_composed_addon_dependencies_skip_a_bare_host(tmp_path: Path) -> None:
    """A unit-test or bare project with no pyproject is an explicit no-op."""

    addon = _app_config(tmp_path / "fake-addon", "example.fake_bare", ("alpha>=1",))
    host = tmp_path / "host"
    host.mkdir()

    projection = AddonDependencyGroup.from_app_configs((addon,), project_dir=host)

    assert projection.write() is AddonDependencyGroupResult.SKIPPED_NO_PYPROJECT
    assert projection.check() is AddonDependencyGroupResult.SKIPPED_NO_PYPROJECT
    assert not (host / "pyproject.toml").exists()


def test_host_build_projects_and_checks_dependencies(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """The native host command couples compiler output to its packaging contract."""

    host = tmp_path / "host"
    host.mkdir()
    pyproject = host / "pyproject.toml"
    pyproject.write_text('[project]\nname = "host"\nversion = "0.0.0"\n', encoding="utf-8")
    addon = _app_config(tmp_path / "fake-addon", "example.fake_check", ("alpha>=1",))
    runtime = Runtime.discover((addon,), runtime_dir=tmp_path / "runtime")
    monkeypatch.setattr(Runtime, "from_django", classmethod(lambda cls: runtime))
    monkeypatch.setattr("angee.management.commands.angee.find_project_dir", lambda: host)
    command = Command()

    command._handle_build({"check": False})
    assert _read_toml(pyproject)["dependency-groups"]["addons"] == ["alpha>=1"]
    first_stat = pyproject.stat()
    command._handle_build({"check": False})
    assert pyproject.stat().st_mtime_ns == first_stat.st_mtime_ns
    command._handle_build({"check": True})

    pyproject.write_text(pyproject.read_text(encoding="utf-8").replace("alpha>=1", "stale>=1"), encoding="utf-8")
    with pytest.raises(CommandError, match="host addon dependency group is stale"):
        command._handle_build({"check": True})

    pyproject.unlink()
    command._handle_build({"check": True})


def test_host_build_reports_a_missing_project_directory(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str],
) -> None:
    """The command reports a bare host without asking the compiler about packaging."""

    addon = _app_config(tmp_path / "fake-addon", "example.fake_no_project", ("alpha>=1",))
    runtime = Runtime.discover((addon,), runtime_dir=tmp_path / "runtime")
    monkeypatch.setattr(Runtime, "from_django", classmethod(lambda cls: runtime))
    monkeypatch.setattr("angee.management.commands.angee.find_project_dir", lambda: None)

    Command()._handle_build({"check": False})

    assert "addon dependencies skipped-no-project-dir" in capsys.readouterr().out


def test_composed_addon_dependency_write_wraps_os_errors(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Atomic replacement failures reach the command as clean runtime errors."""

    host = tmp_path / "host"
    host.mkdir()
    (host / "pyproject.toml").write_text('[project]\nname = "host"\nversion = "0.0.0"\n', encoding="utf-8")
    addon = _app_config(tmp_path / "fake-addon", "example.fake_write_error", ("alpha>=1",))

    def fail_write(*_args: object, **_kwargs: object) -> None:
        raise OSError("read-only pyproject")

    monkeypatch.setattr(dependencies_module, "write_block", fail_write)

    with pytest.raises(RuntimeError, match="read-only pyproject"):
        AddonDependencyGroup.from_app_configs((addon,), project_dir=host).write()
