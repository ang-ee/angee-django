import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { compile } from "tailwindcss";
import { resolveConfig } from "vite";
import { isExportStory, storyNameFromExport, toId } from "storybook/internal/csf";
import { COMPONENT_KINDS, REGION_PLACES, parseCatalog } from "../../ui/src/catalog-schema.ts";

export const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
export const walk = directory => readdirSync(directory, { withFileTypes: true })
  .sort((a, b) => a.name.localeCompare(b.name, "en"))
  .flatMap(entry => entry.isDirectory() ? walk(join(directory, entry.name)) : [join(directory, entry.name)]);
export const unwrap = node => {
  while (node && (ts.isAsExpression(node) || ts.isSatisfiesExpression(node) || ts.isParenthesizedExpression(node))) node = node.expression;
  return node;
};
const tags = node => Object.fromEntries(ts.getJSDocTags(node).map(tag => [
  tag.tagName.text, typeof tag.comment === "string" ? tag.comment : (tag.comment ?? []).map(part => part.text).join(""),
]));
export const canonical = value => `${JSON.stringify(value, null, 2)}\n`;

/** CSS is the owner; the public stylesheet export locates its token sources. */
export function generateTokenNames() {
  const manifest = JSON.parse(readFileSync(join(root, "packages/ui/package.json"), "utf8"));
  const directory = dirname(resolve(root, "packages/ui", manifest.exports["./styles.css"]));
  return [...new Set(walk(directory).filter(file => file.endsWith(".css")).flatMap(file =>
    [...readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/(--[\w-]+)\s*:/g)].map(match => match[1]),
  ))].sort();
}

export const tokenModule = names => `// Generated by Storybook's catalog:generate from the public stylesheet owner.\nexport const tokenNames = ${JSON.stringify(names, null, 2)} as const;\n`;

/** Use the installed Tailwind compiler to resolve production utility references. */
export async function compileUtilities() {
  const config = await resolveConfig({ configFile: false, root: join(root, "packages/storybook") }, "build");
  const resolveStyle = config.createResolver({ conditions: ["style"], mainFields: ["style"], extensions: [".css"] });
  return compile('@import "tailwindcss/index.css"; @import "@angee/ui/styles.css";', {
    base: join(root, "packages/storybook"),
    async loadStylesheet(id, base) {
      const file = await resolveStyle(id, join(base, "entry.css"));
      if (!file) throw new Error(`Unresolved stylesheet: ${id} from ${base}`);
      return { path: file, base: dirname(file), content: readFileSync(file, "utf8") };
    },
  });
}

/** One compiler program supplies export identity, declarations and CSF references. */
export function catalogSources() {
  const roots = ["app", "ui"].map(name => join(root, `packages/${name}/src/index.ts`));
  const storyFiles = walk(join(root, "packages/storybook/src/stories")).filter(file => /\.stories\.tsx?$/.test(file));
  const program = ts.createProgram([...roots, ...storyFiles], {
    module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler, jsx: ts.JsxEmit.ReactJSX,
    allowJs: true, resolveJsonModule: true, skipLibCheck: true,
  });
  const checker = program.getTypeChecker();
  const targetOf = symbol => {
    while (symbol?.flags & ts.SymbolFlags.Alias) symbol = checker.getImmediateAliasedSymbol(symbol);
    return symbol;
  };
  const exports = roots.flatMap(file => {
    const source = program.getSourceFile(file);
    const pkg = file.includes("/app/") ? "@angee/app" : "@angee/ui";
    const directory = dirname(file);
    return checker.getExportsOfModule(checker.getSymbolAtLocation(source)).flatMap(symbol => {
      const target = targetOf(symbol);
      if (!(target?.flags & ts.SymbolFlags.Value)) return [];
      let declaration = target.valueDeclaration ?? target.declarations?.[0];
      let local = symbol;
      let reexport;
      while (local?.flags & ts.SymbolFlags.Alias) {
        const candidate = local.declarations?.[0];
        if (candidate?.getSourceFile().fileName.startsWith(directory)) reexport = candidate;
        local = checker.getImmediateAliasedSymbol(local);
      }
      const upstream = !declaration?.getSourceFile().fileName.startsWith(directory);
      if (upstream) declaration = reexport;
      if (!declaration) throw new Error(`No owning declaration for ${pkg}:${symbol.name}`);
      return [{
        package: pkg, name: symbol.name, symbol, target, declaration, upstream,
        source: relative(root, declaration.getSourceFile().fileName),
        tags: tags(declaration),
      }];
    });
  }).sort((a, b) => `${a.package}:${a.name}`.localeCompare(`${b.package}:${b.name}`, "en"));
  return { program, checker, exports, storyFiles, targetOf };
}

export function symbolCategory(entry, checker) {
  if (/^use[A-Z]/.test(entry.name)) return "hook";
  const type = checker.getTypeOfSymbolAtLocation(entry.target, entry.declaration);
  if (type.getProperty("variants")) return "value";
  if (/^[A-Z][a-z]/.test(entry.name) && type.getCallSignatures().length) return "component";
  if (/^[A-Z][a-z]/.test(entry.name) && type.getProperty("Root")) return "namespace";
  return "value";
}

/** CSF owns story ids and explicit owner claims; unrelated JSX is not coverage. */
export function catalogStories(sources) {
  const { program, checker, exports, storyFiles, targetOf } = sources;
  const byTarget = new Map();
  for (const entry of exports) {
    const entries = byTarget.get(entry.target) ?? [];
    entries.push(entry); byTarget.set(entry.target, entries);
  }
  function object(node) {
    node = unwrap(node);
    if (node && ts.isIdentifier(node)) {
      const symbol = checker.getSymbolAtLocation(node);
      node = unwrap(symbol?.valueDeclaration?.initializer);
    }
    return node && ts.isObjectLiteralExpression(node) ? node : undefined;
  }
  const property = (node, name) => object(node)?.properties.find(p => p.name?.getText().replaceAll('"', "") === name)?.initializer;
  const literal = node => node && ts.isStringLiteralLike(unwrap(node)) ? unwrap(node).text : undefined;
  const stories = [];
  for (const file of storyFiles) {
    const source = program.getSourceFile(file);
    const meta = source.statements.find(statement => ts.isExportAssignment(statement))?.expression;
    const title = literal(property(meta, "title"));
    if (!title) continue;
    const metaId = literal(property(meta, "id")) ?? title;
    const references = new Set();
    function visit(node) {
      if (ts.isIdentifier(node)) {
        const target = targetOf(checker.getSymbolAtLocation(node));
        for (const entry of byTarget.get(target) ?? []) references.add(`${entry.package}:${entry.name}`);
      }
      ts.forEachChild(node, visit);
    }
    visit(source);
    function owners(expression) {
      expression = unwrap(expression);
      if (!expression) return [];
      if (ts.isArrayLiteralExpression(expression)) return expression.elements.flatMap(owners);
      if (ts.isStringLiteralLike(expression)) {
        const matches = exports.filter(entry => entry.name === expression.text || `${entry.package}:${entry.name}` === expression.text);
        if (matches.length !== 1) throw new Error(`${relative(root, file)}: ambiguous or missing owner ${expression.text}`);
        return matches;
      }
      const location = ts.isPropertyAccessExpression(expression) ? expression.name : expression;
      return byTarget.get(targetOf(checker.getSymbolAtLocation(location))) ?? [];
    }
    for (const statement of source.statements) {
      if (!ts.isVariableStatement(statement) || !statement.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) continue;
      for (const declaration of statement.declarationList.declarations) {
        const name = declaration.name.getText(source);
        if (!isExportStory(name, {})) continue;
        // A story's display-name override does not change its export-based id.
        const storyName = storyNameFromExport(name);
        const explicit = property(property(declaration.initializer, "parameters"), "owner")
          ?? property(property(meta, "parameters"), "owner");
        const owned = owners(explicit ?? property(meta, "component"));
        if (explicit && !owned.length) throw new Error(`${relative(root, file)}: owner must name a public catalog export`);
        const ids = [...new Set(owned.map(entry => `${entry.package}:${entry.name}`))].sort();
        for (const owner of ids) if (!references.has(owner)) throw new Error(`${file} claims ${owner} without referencing its export identifier.`);
        stories.push({ id: toId(metaId, storyName), file: relative(root, file), owners: ids, preferred: name === "Default" });
      }
    }
  }
  return stories.sort((a, b) => a.id.localeCompare(b.id, "en"));
}

export function generateCatalog(sources = catalogSources()) {
  const { exports, checker, program } = sources;
  const byId = new Map(exports.map(entry => [`${entry.package}:${entry.name}`, entry]));
  const resolved = new Map();
  function resolveEntry(entry, trail = new Set()) {
    const id = `${entry.package}:${entry.name}`;
    if (resolved.has(id)) return resolved.get(id);
    if (trail.has(id)) throw new Error(`Catalog owner cycle: ${[...trail, id].join(" → ")}`);
    trail.add(id);
    const metadata = entry.tags;
    let kind = metadata.kind === "null" ? null : metadata.kind;
    let region = metadata.region;
    let reason = metadata.reason;
    let owner;
    if (entry.upstream) {
      kind = null; reason = "upstream re-export";
    } else if (metadata.owner) {
      owner = metadata.owner.includes(":") ? metadata.owner : `${entry.package}:${metadata.owner}`;
      const target = byId.get(owner);
      if (!target) throw new Error(`${id}: unknown @owner ${owner}`);
      ({ kind, region, reason } = resolveEntry(target, new Set(trail)));
    }
    if (kind === undefined || (kind !== null && !COMPONENT_KINDS.includes(kind))) throw new Error(`${id}: missing or invalid @kind/@owner`);
    if (kind === null && !reason) throw new Error(`${id}: infrastructure needs @reason`);
    if (kind === "region" && !REGION_PLACES.includes(region)) throw new Error(`${id}: invalid @region ${region}`);
    if (kind !== "region" && region) throw new Error(`${id}: only regions name shell places`);
    if (kind !== null && symbolCategory(entry, checker) === "hook" && !owner) throw new Error(`${id}: a classified hook needs @owner`);
    if (kind === "token" && ["component", "namespace", "hook"].includes(symbolCategory(entry, checker))) throw new Error(`${id}: a token must be a value or recipe`);
    const result = {
      package: entry.package, name: entry.name, source: entry.source, kind,
      ...(owner ? { owner } : {}), ...(region ? { region } : {}),
      ...(kind === null ? { reason } : {}),
      status: Object.hasOwn(metadata, "deprecated") ? "deprecated" : "stable",
      storyId: null,
    };
    resolved.set(id, result);
    return result;
  }
  const entries = exports.map(entry => resolveEntry(entry)).sort((a, b) => {
    const left = `${a.package}:${a.name}`, right = `${b.package}:${b.name}`;
    return left < right ? -1 : left > right ? 1 : 0;
  });
  const stories = catalogStories(sources);
  for (const entry of entries) {
    entry.storyId = stories.filter(story => story.owners.includes(`${entry.package}:${entry.name}`))
      .sort((a, b) => Number(b.preferred) - Number(a.preferred) || a.id.localeCompare(b.id, "en"))[0]?.id ?? null;
  }
  const places = new Map();
  // Internal annotated owners also matter: FormViewRecordHeader need not be
  // promoted into the public barrel just to report its duplicate anatomy.
  const seen = new Set();
  for (const source of program.getSourceFiles().filter(source => /packages\/(?:ui|app)\/src\//.test(source.fileName) && !source.fileName.includes("/node_modules/"))) {
    for (const statement of source.statements) {
      const metadata = tags(statement);
      if (metadata.kind !== "region") continue;
      const name = ts.isVariableStatement(statement) ? statement.declarationList.declarations[0]?.name.getText(source) : statement.name?.getText(source);
      if (!name || !REGION_PLACES.includes(metadata.region)) throw new Error(`${source.fileName}: invalid region annotation`);
      const key = `${relative(root, source.fileName)}:${name}`;
      if (seen.has(key)) continue;
      seen.add(key);
      const list = places.get(metadata.region) ?? [];
      list.push({ name, source: relative(root, source.fileName) }); places.set(metadata.region, list);
    }
  }
  const regionDuplications = Object.fromEntries([...places].filter(([, owners]) => owners.length > 1)
    .sort(([a], [b]) => a.localeCompare(b, "en"))
    .map(([place, owners]) => [place, owners.sort((a, b) => a.name.localeCompare(b.name, "en"))]));
  return { entries: parseCatalog(entries), stories, regionDuplications };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = generateCatalog();
  const output = canonical(result.entries);
  const file = join(root, "packages/ui/src/catalog-data.json");
  const tokensFile = join(root, "packages/ui/src/token-names.ts");
  const tokens = tokenModule(generateTokenNames());
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8") !== output) throw new Error("Catalog drift: run the Storybook catalog:generate script.");
    if (readFileSync(tokensFile, "utf8") !== tokens) throw new Error("Token-name drift: run the Storybook catalog:generate script.");
  } else {
    writeFileSync(file, output);
    writeFileSync(tokensFile, tokens);
  }
  console.log(JSON.stringify({
    counts: Object.fromEntries(["@angee/app", "@angee/ui"].map(pkg => [pkg, Object.fromEntries(
      [...COMPONENT_KINDS, null].map(kind => [kind ?? "none", result.entries.filter(entry => entry.package === pkg && entry.kind === kind).length]),
    )])),
    stories: { derived: result.entries.filter(entry => entry.storyId).length, gap: result.entries.filter(entry => !entry.storyId).length },
    regionDuplications: result.regionDuplications,
  }, null, 2));
}
